import { Sparkles } from "lucide-react";
import { Progress } from "@/components/ui/progress";

export function PredictionWidget({
  predicted,
  expected,
  confidence,
  caption = "Attendance forecast generated by attendance-predictor v2.4",
}: {
  predicted: number;
  expected: number;
  confidence: number;
  caption?: string;
}) {
  const variance = Math.round(((predicted - expected) / Math.max(expected, 1)) * 100);
  return (
    <div className="surface-card relative overflow-hidden p-5">
      <div className="pointer-events-none absolute inset-0 [background-image:var(--gradient-surface)]" />
      <div className="relative">
        <div className="flex items-center gap-2">
          <span className="grid size-8 place-items-center rounded-xl bg-primary/10 text-primary">
            <Sparkles className="size-4" aria-hidden="true" />
          </span>
          <div>
            <p className="text-sm font-semibold">AI Prediction</p>
            <p className="text-xs text-muted-foreground">{caption}</p>
          </div>
        </div>
        <div className="mt-5 flex items-end gap-3">
          <p className="text-4xl font-semibold tabular-nums">{predicted.toLocaleString()}</p>
          <p className="pb-1 text-sm text-muted-foreground">
            of {expected.toLocaleString()} expected
            <span className={variance >= 0 ? " text-success" : " text-warning"}>
              {" "}
              ({variance >= 0 ? "+" : ""}
              {variance}%)
            </span>
          </p>
        </div>
        <div className="mt-4">
          <div className="flex items-center justify-between text-xs font-medium">
            <span className="text-muted-foreground">Prediction confidence</span>
            <span className="tabular-nums">{confidence}%</span>
          </div>
          <Progress value={confidence} className="mt-2 h-2" />
        </div>
      </div>
    </div>
  );
}
